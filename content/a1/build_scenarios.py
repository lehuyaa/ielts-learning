def build():
    scenarios = []
    order = 0
    for week, (group, items) in WEEKS.items():
        for lesson_number, (key, title, situation, role, task, patterns, opening, turns) in enumerate(items, start=1):
            order += 1
            scenario = {
                "slug": f"a1-w{week}-{key}", "title": title, "description": situation,
                "cefrLevel": "A1", "role": role, "task": task, "targetPatterns": patterns,
                "maxTurns": turns, "openingLine": opening, "group": group,
                "duration": "5 min", "orderIndex": order,
            }
            if week == 1:
                scenario["passageSlug"] = f"a1-w1-l{lesson_number}-dialogue"
            scenarios.append(scenario)
        title, situation, role, task, patterns, opening, turns = CHECKPOINTS[week]
        order += 1
        scenarios.append({
            "slug": f"a1-w{week}-checkpoint", "title": title, "description": situation,
            "cefrLevel": "A1", "role": role, "task": task, "targetPatterns": patterns,
            "maxTurns": turns, "openingLine": opening, "group": group,
            "duration": "7 min", "orderIndex": order,
        })
    return {"version": 1, "courseSlug": "foundation-english", "cefrLevel": "A1", "scenarios": scenarios}


if __name__ == "__main__":
    bundle = build()
    with open("a1-scenarios.json", "w", encoding="utf-8") as handle:
        json.dump(bundle, handle, ensure_ascii=False, indent=2)
        handle.write("\n")
    print(f"{len(bundle['scenarios'])} scenarios")
