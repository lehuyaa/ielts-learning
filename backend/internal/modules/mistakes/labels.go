package mistakes

import "strings"

// Skill kinds group the mistake log and decide how extra practice is built.
const (
	KindGrammar   = "GRAMMAR"
	KindSound     = "SOUND"
	KindVocab     = "VOCABULARY"
	KindListening = "LISTENING"
	KindReading   = "READING"
	KindSpeaking  = "SPEAKING"
	KindOther     = "OTHER"
)

// SkillKind classifies a skill tag such as "grammar:g1-to-be" or "sound:θ-s".
func SkillKind(tag string) string {
	prefix, _, _ := strings.Cut(tag, ":")
	switch prefix {
	case "grammar":
		return KindGrammar
	case "sound", "stress":
		return KindSound
	case "vocab", "spelling", "word-choice":
		return KindVocab
	case "listening":
		return KindListening
	case "reading":
		return KindReading
	case "speaking":
		return KindSpeaking
	default:
		return KindOther
	}
}

// SkillLabel is a Vietnamese name for a skill tag; grammarTitles maps
// grammar slugs to their titles.
func SkillLabel(tag string, grammarTitles map[string]string) string {
	prefix, rest, _ := strings.Cut(tag, ":")
	switch prefix {
	case "grammar":
		if title := grammarTitles[rest]; title != "" {
			return "Ngữ pháp: " + title
		}
		return "Ngữ pháp: " + rest
	case "sound":
		switch rest {
		case "ending-s":
			return "Phát âm đuôi -s / -es"
		case "ending-ed":
			return "Phát âm đuôi -ed"
		case "clusters":
			return "Cụm phụ âm cuối"
		}
		if a, b, pair := strings.Cut(rest, "-"); pair && a != "" && b != "" {
			return "Phân biệt /" + a + "/ và /" + b + "/"
		}
		return "Âm /" + rest + "/"
	case "stress":
		return "Trọng âm"
	case "listening":
		switch rest {
		case "dictation":
			return "Nghe chép chính tả"
		case "numbers":
			return "Nghe số"
		}
		return "Nghe hiểu"
	case "reading":
		return "Đọc hiểu"
	case "speaking":
		return "Nói"
	case "vocab":
		if rest != "" {
			return "Từ vựng: " + rest
		}
		return "Từ vựng"
	case "spelling":
		return "Chính tả"
	case "word-choice":
		return "Dùng từ"
	}
	if tag == "" {
		return "Khác"
	}
	return tag
}

// PracticeFromBank reports whether extra practice for a tag is drawn from
// existing exercises (sounds, stress, dictation, numbers carry their own
// audio) rather than generated by AI.
func PracticeFromBank(tag string) bool {
	switch SkillKind(tag) {
	case KindSound:
		return true
	case KindListening:
		return tag == "listening:dictation" || tag == "listening:numbers"
	}
	return false
}

// Practiceable reports whether extra practice can be built for a tag (Task 74).
// Reading / listening comprehension and speaking need their passage or a
// conversation, so they are practised in lessons instead.
func Practiceable(tag string) bool {
	switch SkillKind(tag) {
	case KindGrammar, KindVocab, KindOther:
		return tag != ""
	}
	return PracticeFromBank(tag)
}
